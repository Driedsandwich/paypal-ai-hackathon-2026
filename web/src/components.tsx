import { useState, type ReactNode } from "react";
import { api, ApiError, type Proposal } from "./api";

export function ErrorBox({ error }: { error: unknown }) {
  if (!error) return null;
  if (error instanceof ApiError) {
    const b = error.body;
    return (
      <div className="error" role="alert">
        <strong>{b.message}</strong>
        {b.issues && <ul>{b.issues.map((i) => <li key={i}>{i}</li>)}</ul>}
        {b.paypal && (
          <p>
            PayPal: {b.paypal.name ?? b.paypal.status} {b.paypal.issues?.join("; ")}
            {b.paypal.debugId && <> · debug_id <code>{b.paypal.debugId}</code></>}
          </p>
        )}
        {b.retryAfterSeconds !== undefined && <p>Try again in about {Math.ceil(b.retryAfterSeconds / 60)} minute(s).</p>}
      </div>
    );
  }
  return <div className="error" role="alert">{error instanceof Error ? error.message : String(error)}</div>;
}

/** Runs an async action with busy/error state. */
export function useAction<A extends unknown[], T>(fn: (...args: A) => Promise<T>) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<unknown>(null);
  const run = async (...args: A): Promise<T | undefined> => {
    setBusy(true);
    setError(null);
    try {
      return await fn(...args);
    } catch (e) {
      setError(e);
      return undefined;
    } finally {
      setBusy(false);
    }
  };
  return { run, busy, error };
}

export function AiBadge({ by }: { by?: { provider: string; model?: string } }) {
  if (!by) return null;
  return <span className="badge" title="Generated by AI">AI: {by.provider}{by.model ? ` · ${by.model}` : ""}</span>;
}

const STATUS_CLASS: Record<Proposal["status"], string> = { pending: "warn", executing: "", executed: "ok", failed: "err", rejected: "", unknown: "err", obsolete: "", expired: "" };
const STATUS_LABEL: Record<Proposal["status"], string> = {
  pending: "pending",
  executing: "executing",
  executed: "executed",
  failed: "failed",
  rejected: "rejected",
  unknown: "unknown: needs checking",
  obsolete: "obsolete",
  expired: "expired",
};

/** AI text the seller sends to the buyer by DM (these sellers talk to buyers in social media DMs). */
export function CopyForDm({ text }: { text: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <div className="ai-note">
      <label>Copy for DM (not sent by PayPal)</label>
      <textarea readOnly value={text} />
      <button className="secondary" onClick={() => void navigator.clipboard?.writeText(text).then(() => setCopied(true))}>{copied ? "Copied" : "Copy"}</button>
    </div>
  );
}

/** Shows what will be sent to PayPal, with Approve / Reject. The server enforces the gate. */
export function ProposalCard({ proposal, onChange, children }: { proposal: Proposal; onChange?: (p: Proposal) => void; children?: ReactNode }) {
  const [p, setP] = useState(proposal);
  const act = useAction(async (verb: "approve" | "reject") => {
    const next = await api.post<Proposal>(`/api/proposals/${p.id}/${verb}`);
    setP(next);
    onChange?.(next);
  });
  return (
    <div className="card" style={{ border: "1px solid #ddd", borderRadius: 8, padding: "0.75rem", margin: "0.5rem 0", background: "#fff" }}>
      <div>
        <strong>{p.title}</strong>
        <span className={`badge ${STATUS_CLASS[p.status]}`}>{STATUS_LABEL[p.status]}</span>
      </div>
      {children}
      {p.copy_for_dm && <CopyForDm text={p.copy_for_dm} />}
      <details open={p.status === "pending"}>
        <summary className="muted">Payload sent to PayPal on approval ({p.kind}; buyers shown by demo alias)</summary>
        <pre>{JSON.stringify(p.payload, (k, v) => (k === "base64" && typeof v === "string" ? `${v.slice(0, 24)}… (${v.length} chars)` : v), 2)}</pre>
      </details>
      {p.status === "pending" && (
        <>
          <button className="primary" disabled={act.busy} onClick={() => void act.run("approve")}>Approve and send</button>
          <button className="danger" disabled={act.busy} onClick={() => void act.run("reject")}>Reject</button>
        </>
      )}
      {p.status === "executed" && <pre>{JSON.stringify(p.result, null, 2)}</pre>}
      {(p.status === "unknown" || p.status === "obsolete" || p.status === "expired") && <div className="error">{p.error?.message}</div>}
      {p.status === "failed" && (
        <div className="error">
          {p.error?.message}
          {p.error?.paypal?.debugId && <> · debug_id <code>{p.error.paypal.debugId}</code></>}
          {p.error?.paypal?.issues && <> · {p.error.paypal.issues.join("; ")}</>}
        </div>
      )}
      <ErrorBox error={act.error} />
    </div>
  );
}
